-- Chạy bằng vai trò quản trị khi người dùng đã cho phép tạo tài nguyên cloud.
-- Không chạy tự động. Thay USER_NAME trước khi GRANT ROLE.
-- Initial conservative allowance: 5 Snowflake credits, NOT 5 USD.
-- Never reset automatically. Review account trial balance before any increase.
CREATE RESOURCE MONITOR IF NOT EXISTS OLIST_TRIAL_GUARD WITH CREDIT_QUOTA=5
 FREQUENCY=NEVER START_TIMESTAMP=IMMEDIATELY
 TRIGGERS ON 80 PERCENT DO NOTIFY ON 90 PERCENT DO SUSPEND ON 100 PERCENT DO SUSPEND_IMMEDIATE;
CREATE WAREHOUSE IF NOT EXISTS OLIST_DEMO_WH WITH WAREHOUSE_SIZE='XSMALL'
 AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
ALTER WAREHOUSE OLIST_DEMO_WH SET STATEMENT_TIMEOUT_IN_SECONDS=120;
ALTER WAREHOUSE OLIST_DEMO_WH SET RESOURCE_MONITOR=OLIST_TRIAL_GUARD
 STATEMENT_QUEUED_TIMEOUT_IN_SECONDS=60 MAX_CLUSTER_COUNT=1;
CREATE DATABASE IF NOT EXISTS OLIST_DEMO;
CREATE SCHEMA IF NOT EXISTS OLIST_DEMO.RAW;
CREATE SCHEMA IF NOT EXISTS OLIST_DEMO.ANALYTICS;
-- Empty replay tables allow batch-only dbt builds before the first simulated replay load.
CREATE TABLE IF NOT EXISTS OLIST_DEMO.RAW.LIFECYCLE_EVENTS (DATA VARIANT, ROW_KEY VARCHAR, DATASET_VERSION VARCHAR, DATASET_KIND VARCHAR);
CREATE TABLE IF NOT EXISTS OLIST_DEMO.RAW.REPLAY_METRICS (DATA VARIANT, ROW_KEY VARCHAR, DATASET_VERSION VARCHAR, DATASET_KIND VARCHAR);
CREATE ROLE IF NOT EXISTS OLIST_LOADER;
CREATE ROLE IF NOT EXISTS OLIST_TRANSFORMER;
CREATE ROLE IF NOT EXISTS OLIST_READER;
GRANT USAGE ON WAREHOUSE OLIST_DEMO_WH TO ROLE OLIST_LOADER;
GRANT USAGE ON DATABASE OLIST_DEMO TO ROLE OLIST_LOADER;
GRANT USAGE ON SCHEMA OLIST_DEMO.RAW TO ROLE OLIST_LOADER;
GRANT CREATE TABLE, CREATE STAGE ON SCHEMA OLIST_DEMO.RAW TO ROLE OLIST_LOADER;
GRANT SELECT, INSERT, UPDATE ON TABLE OLIST_DEMO.RAW.LIFECYCLE_EVENTS TO ROLE OLIST_LOADER;
GRANT SELECT, INSERT, UPDATE ON TABLE OLIST_DEMO.RAW.REPLAY_METRICS TO ROLE OLIST_LOADER;
GRANT USAGE ON WAREHOUSE OLIST_DEMO_WH TO ROLE OLIST_TRANSFORMER;
GRANT USAGE ON DATABASE OLIST_DEMO TO ROLE OLIST_TRANSFORMER;
GRANT USAGE ON SCHEMA OLIST_DEMO.RAW TO ROLE OLIST_TRANSFORMER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OLIST_DEMO.RAW TO ROLE OLIST_TRANSFORMER;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA OLIST_DEMO.ANALYTICS TO ROLE OLIST_TRANSFORMER;
GRANT USAGE ON WAREHOUSE OLIST_DEMO_WH TO ROLE OLIST_READER;
GRANT USAGE ON DATABASE OLIST_DEMO TO ROLE OLIST_READER;
GRANT USAGE ON SCHEMA OLIST_DEMO.ANALYTICS TO ROLE OLIST_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA OLIST_DEMO.ANALYTICS TO ROLE OLIST_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA OLIST_DEMO.ANALYTICS TO ROLE OLIST_READER;
